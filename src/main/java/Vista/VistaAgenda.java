    private void btnbuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnbuscarActionPerformed
        
        String telefono = controlador.buscarTelefono(txtnombreconctacto.getText().trim());

    if (telefono == null) {
        lblbusquedaresultado.setText("Contacto no encontrado");
    } else {
        lblbusquedaresultado.setText(telefono);
    }
    
    }//GEN-LAST:event_btnbuscarActionPerformed

